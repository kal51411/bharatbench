class MockLLMProvider(BaseLLMProvider):
    """
    Deterministic mock provider for testing and demonstration.
    NEVER mix mock responses with real research data.
    """

    PROVIDER_NAME = "mock"
    MOCK_MODELS = ["mock-demo-v1", "mock-demo-v2"]

    @property
    def provider_name(self) -> str:
        return self.PROVIDER_NAME

    @property
    def display_name(self) -> str:
        return "Mock / DEMO Provider"

    def get_available_models(self) -> List[str]:
        return self.MOCK_MODELS

    def is_configured(self) -> bool:
        return True  # Always available

    def validate_configuration(self) -> tuple[bool, Optional[str]]:
        return True, None

    async def generate(self, request: LLMRequest, model_name: str) -> LLMResponse:
        # Simulate a small latency for realism
        start = time.monotonic()
        time.sleep(0.05)  # 50ms simulated latency

        # Find best matching response key
        prompt_lower = request.prompt.lower()
        response_text = DEMO_RESPONSES["__default__"]
        for keyword, demo_response in DEMO_RESPONSES.items():
            if keyword != "__default__" and keyword in prompt_lower:
                response_text = demo_response
                break

        # Different model versions give slightly different responses
        if model_name == "mock-demo-v2":
            response_text = response_text + " [v2]"

        latency_ms = int((time.monotonic() - start) * 1000)

        # Deterministic token count based on content
        word_count = len(response_text.split())
        estimated_tokens = max(word_count * 2, 10)

        return LLMResponse(
            text=response_text,
            model_name=model_name,
            model_version="demo-2024.11",
            input_tokens=len(request.prompt.split()) * 2,
            output_tokens=estimated_tokens,
            latency_ms=latency_ms,
            is_demo=True,
        )
